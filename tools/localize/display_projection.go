func displayName(name string) string {
	parts := strings.Split(name, ".")
	return "FnDisplay" + parts[len(parts)-1]
}

// projectDisplay emits private copies of reviewed display producers. Canonical
// APIs, tables and routing caches are never translated in place.
func projectDisplay(root, catalog, reportPath string) error {
	index, err := displaySources(root)
	if err != nil {
		return err
	}
	data, err := os.ReadFile(catalog)
	if err != nil {
		return err
	}
	var reviewed []entry
	if err := json.Unmarshal(data, &reviewed); err != nil {
		return err
	}
	translations := map[string]entry{}
	for _, item := range reviewed {
		if item.Kind == "config-display" && item.Decision == "translate" {
			translations[fmt.Sprintf("%s:%d", item.File, item.Start)] = item
		}
	}
	marked := func(file string, node ast.Node) bool {
		found := false
		ast.Inspect(node, func(node ast.Node) bool {
			if lit, ok := node.(*ast.BasicLit); ok && lit.Kind == token.STRING {
				_, exists := translations[fmt.Sprintf("%s:%d", file, index.fset.Position(lit.Pos()).Offset)]
				found = found || exists
			}
			return true
		})
		return found
	}
	functions, values := map[string]bool{}, map[string]bool{}
	for name, fn := range index.functions {
		if index.reachable[name] && marked(fn.file, fn.node) {
			functions[name] = true
		}
	}
	for name, value := range index.values {
		if marked(value.file, value.node) {
			values[name] = true
		}
	}
	for changed := true; changed; {
		changed = false
		for name, fn := range index.functions {
			if !index.reachable[name] || functions[name] || displayBarriers[name] {
				continue
			}
			for child := range fn.calls {
				if functions[child] {
					functions[name], changed = true, true
				}
			}
			for value := range fn.values {
				if values[value] {
					functions[name], changed = true, true
				}
			}
		}
	}
	for _, root := range displayRoots {
		functions[root] = true
	}
	files := map[string]*ast.File{}
	applied := map[string]int{}
	imports := map[string][]*ast.ImportSpec{}
	add := func(file string, decl ast.Decl, specs []*ast.ImportSpec) {
		if files[file] == nil {
			files[file] = &ast.File{Name: ast.NewIdent("config")}
			imports[file] = specs
		}
		files[file].Decls = append(files[file].Decls, decl)
	}
	for _, name := range sortedNames(functions) {
		fn := index.functions[name]
		if err := index.checkProjection(fn); err != nil {
			return err
		}
		if err := index.rewriteDisplay(fn.file, fn.node, translations, functions, values, applied); err != nil {
			return err
		}
		fn.node.Name.Name = displayName(name)
		add(fn.file, fn.node, fn.imports)
	}
	for _, name := range sortedNames(values) {
		value := index.values[name]
		if err := index.rewriteDisplay(value.file, value.node, translations, functions, values, applied); err != nil {
			return err
		}
		add(value.file, &ast.GenDecl{Tok: value.kind, Specs: []ast.Spec{value.node}}, value.imports)
	}
	for _, entry := range translations {
		if applied[entry.ID] != 1 {
			return fmt.Errorf("display translation must be applied exactly once: %s (%d)", entry.ID, applied[entry.ID])
		}
	}
	for file, generated := range files {
		used := map[string]bool{}
		ast.Inspect(generated, func(node ast.Node) bool {
			if sel, ok := node.(*ast.SelectorExpr); ok {
				if owner, ok := sel.X.(*ast.Ident); ok {
					used[owner.Name] = true
				}
			}
			return true
		})
		var retained []ast.Spec
		for _, spec := range imports[file] {
			name := importName(spec)
			if used[name] {
				retained = append(retained, spec)
			}
		}
		if len(retained) > 0 {
			generated.Decls = append([]ast.Decl{&ast.GenDecl{Tok: token.IMPORT, Specs: retained}}, generated.Decls...)
		}
		var output bytes.Buffer
		output.WriteString("// Code generated by FnTuiOS display projection; DO NOT EDIT.\n")
		if err := format.Node(&output, index.fset, generated); err != nil {
			return err
		}
		path := filepath.Join(root, "internal/config/fntuios_display_"+filepath.Base(file))
		if err := os.WriteFile(path, output.Bytes(), 0644); err != nil {
			return err
		}
	}
	if reportPath != "" {
		data, _ := json.MarshalIndent(map[string]any{"roots": displayRoots, "functions": sortedNames(functions), "values": sortedNames(values), "applied_contexts": applied, "canonical_barriers": sortedNames(displayBarriers), "unprojected_input": []string{"UserConfig.LoadWarnings: preformatted loader/include/reload history"}}, "", "  ")
		return os.WriteFile(reportPath, append(data, '\n'), 0644)
	}
	return nil
}

func sortedNames(set map[string]bool) []string {
	var names []string
	for name := range set {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func importName(spec *ast.ImportSpec) string {
	if spec.Name != nil {
		return spec.Name.Name
	}
	path, _ := strconv.Unquote(spec.Path.Value)
	name := filepath.Base(path)
	if len(name) > 1 && name[0] == 'v' && strings.Trim(name[1:], "0123456789") == "" {
		return filepath.Base(filepath.Dir(path))
	}
	return name
}

func (index *displayIndex) rewriteDisplay(file string, node ast.Node, translations map[string]entry, functions, values map[string]bool, applied map[string]int) error {
	var failure error
	var parents []ast.Node
	ast.Inspect(node, func(node ast.Node) bool {
		if node == nil {
			parents = parents[:len(parents)-1]
			return true
		}
		var parent ast.Node
		if len(parents) > 0 {
			parent = parents[len(parents)-1]
		}
		parents = append(parents, node)
		if call, ok := node.(*ast.CallExpr); ok {
			if target := index.callTarget(call.Fun); functions[target] {
				switch function := call.Fun.(type) {
				case *ast.Ident:
					function.Name = displayName(target)
				case *ast.SelectorExpr:
					function.Sel.Name = displayName(target)
				}
			}
		}
		if name, ok := node.(*ast.Ident); ok && values[name.Name] {
			if sel, ok := parent.(*ast.SelectorExpr); ok && sel.Sel == name {
				return true
			}
			if field, ok := parent.(*ast.KeyValueExpr); ok && field.Key == name {
				return true
			}
			if name.Obj == nil || name.Obj.Decl == index.values[name.Name].node {
				name.Name = displayName(name.Name)
			}
		}
		if lit, ok := node.(*ast.BasicLit); ok && lit.Kind == token.STRING {
			key := fmt.Sprintf("%s:%d", file, index.fset.Position(lit.Pos()).Offset)
			if entry, ok := translations[key]; ok {
				source, _ := strconv.Unquote(lit.Value)
				if source != entry.Source {
					failure = fmt.Errorf("display projection source changed: %s", entry.ID)
				} else {
					lit.Value = strconv.Quote(entry.Translation)
					applied[entry.ID]++
				}
			}
		}
		return true
	})
	return failure
}
